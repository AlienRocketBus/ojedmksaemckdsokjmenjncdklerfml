def _章号(名):
    """自档名取章号（⛔汉数字·与 `外声闸` 同法）。取不出者回 0。"""
    _cn = {'零': 0, '〇': 0, '一': 1, '二': 2, '三': 3, '四': 4,
           '五': 5, '六': 6, '七': 7, '八': 8, '九': 9}
    m = re.search(r'第([零〇一二三四五六七八九十百千]+)章', 名)
    if not m:
        return 0
    tot = cur = 0
    for ch in m.group(1):
        if ch in _cn:
            cur = _cn[ch]
        elif ch == '十':
            tot += (cur or 1) * 10; cur = 0
        elif ch == '百':
            tot += (cur or 1) * 100; cur = 0
        elif ch == '千':
            tot += (cur or 1) * 1000; cur = 0
    return tot + cur


