_D = '零〇一二三四五六七八九十百'
# ★1016·X03（391 所逮）：旧式取白文头一个日号作本章之日——391（暗线·霍钧镜）白文不落今日之号，
#   :93 她那封信之首行「第四十四日」遂被认作本章之日（实暗·147）；393 无号则相对日词一律「？」。
#   故：①本章之日先取 施工表锁定行（「主线·第N天」「暗线·第N日」）、次取 总纲 两栏表
#   （与 工具/造式验.py 之 线(n) 同读之表：| N | 主·M |／| N | 暗·M |）；表无本章方退回白文。
#   ②白文退路⛔认引号「」“”之内之号，⛔认信、纸、条上所写之号（其段或上一段提及信／纸条之类）。
# 锁定行之线·日：「（**暗线·第一百四十七日**」或「主线·苏衍**（…）｜**第一百一十九天」——其间夹注可含 | 与括号（322）
_锁定式 = re.compile(r'(主|暗)线·(?:[^\n]{0,120}?｜\**)??第([%s]+)([天日])' % _D)
# 信纸条上之号：本段提及信／纸条之类即去；上一段只认「信」（391:93 之段只书「这一封」，信在上一段）
_物上式 = re.compile(r'封信|信外|信上|信里|信纸|把信|那信|这信|纸条|字条|条子|便条|条上|纸上(?:是|写着|写的|记着|记的)')   # 「送到纸上」係自落，⛔去（359:13）
_信式 = re.compile(r'封信|信外|信上|信里|信纸|把信|那信|这信')


def 表之日(n, 施工=None, 总纲=None):
    """(线, 日, 出处)——先施工表锁定行（其第三栏前 240 字内之线·日），次总纲两栏表；俱无则 (None, None, None)。
    二表俱有而相合，出处书「总纲＝锁定行」；不合则从锁定行，出处书「锁定行≠总纲 主·M」。
    施工／总纲：其文（自测造局用）；缺则读盘。"""
    def 读(名):
        try:
            return io.open(os.path.join(根, '设定', 名), encoding='utf-8').read()
        except OSError:
            return ''
    if 施工 is None:
        施工 = 读('01_镇冢秘术_逐章施工与伏笔回收表.md')
    if 总纲 is None:
        总纲 = 读('02_余章之势_总纲.md')
    锁 = None
    for m in re.finditer(r'^\|\s*%d\s*\|\s*锁定[^|\n]*\|([^\n]*)$' % n, 施工, re.M):
        k = _锁定式.search(m.group(1)[:240])
        if k:
            锁 = (k.group(1), _num(k.group(2)))
            break
    m = re.search(r'\|\s*%d\s*\|\s*(主|暗)·(\d+)(?:—\d+)?[^|\n]*\|' % n, 总纲)   # 两栏逐栏认（同 造式验.线）
    纲 = (m.group(1), int(m.group(2))) if m else None
    if 锁 and 纲:
        return 锁 + (('总纲＝锁定行',) if 锁 == 纲 else ('锁定行≠总纲 %s·%d' % 纲,))
    if 锁:
        return 锁 + ('施工表锁定行',)
    if 纲:
        return 纲 + ('总纲',)
    return None, None, None


def 白文之日(body):
    """白文自落之本日（⛔引号内、⛔信纸条上）：章首八行 → 亲落「写：第N日」 → 头一处；无则 None。"""
    行 = body.split('\n')
    净 = []                                   # 逐行：去引号内，信纸条之段整行去
    前段 = ''                                 # 上一段（＊ 断拍之行不算段）
    for l in 行:
        去 = bool(l.strip()) and bool(_物上式.search(l) or _信式.search(前段))
        净.append('' if 去 else re.sub(r'「[^」\n]*」|“[^”\n]*”', '', l))
        if l.strip() and l.strip() != '＊':
            前段 = l
    日式 = re.compile(r'第([%s]+)[天日]' % _D)
    全 = '\n'.join(净)
    M = (日式.findall('\n'.join(净[:8]))
         or re.findall(r'写：第([%s]+)日' % _D, 全)
         or 日式.findall(全))
    return _num(M[0]) if M else None


def 乙层(n, 文=None, 施工=None, 总纲=None):
    """机器只列单、须人逐条答的。文／施工／总纲：自测造局用，缺则读盘。"""
    if 文 is None:
        章 = 诸章()
        if n not in 章:
            return None
        文 = io.open(章[n], encoding='utf-8').read()
    t = 文
    body = t.split('【本章亮点】')[0]
    行 = body.split('\n')
    # ★0908 二治（290 与 293 两席各自逮出·令§十三「它红在哪一行」）：
    #   ①旧式只认「第N天」，不认「第N日」——而全书暗线诸章之章首皆作「第N日」
    #     （290:5「第九十六日头一件事」），闸遂跳过章首，取到後文某处回指之「第N天」，
    #     於是 290 印「本章为第93天」，其下 24 处相对日词一律少算三天。
    #   ②旧式之字集无「零」——「第一百零四天」不匹配（293:5），闸又往下取，
    #     印「本章为第99天」，其下一路偏五天。
    #   **两处都不是报红，是印了一个错的数给人看**；席若照它答乙层之问，答的是错题。
    #   故：**先自章首八行取，取不着才退回全篇**；字集补「零〇」，并认「日」。
    # ★0926 三治（373 所逮·与 `日差哨.线与日` 同尺同日改）：章首无日时，全篇头一处可能是回指昨日之行
    #   （373「第一百三十七日那一行下头还空着一截」），本日在後文亲落之「写：第一百三十八日」——
    #   **退路之内先取亲落之「写：第N日」（只认日字式），无者方取头一处**。
    # ★1016 四治（X03·391）：表先於白文；白文之退路见 白文之日（⛔引号内、⛔信纸条上）。
    线, 表日, 源 = 表之日(n, 施工, 总纲)
    白日 = 白文之日(body)
    本日 = 表日 if 表日 is not None else 白日
    if 表日 is None:
        源 = '白文' if 白日 is not None else None

    # ①相对日词 → 指向第几天／哪一章
    日 = []
    for i, l in enumerate(行, 1):
        for w, d in 日词.items():
            if w in l:
                日.append((i, w, (本日 - d) if 本日 else None, l.strip()[:52]))
        for m in re.finditer(r'([一二三四五六七八九十]+)天前', l):
            日.append((i, m.group(0), (本日 - _num(m.group(1))) if 本日 else None, l.strip()[:52]))
    # ②本章引了前文哪几句（引号内 ≥6 字者）
    引 = sorted({q for q in re.findall(r'[“「]([^”」]{6,40})[”」]', body)})
    # ③本章立了哪几条令
    令 = [(i, l.strip()[:60]) for i, l in enumerate(行, 1)
          if re.search(r'(往后|以后|从今天起|往下|凡)[^。]{0,24}(不许|不准|别|得|须|一律|都要)', l)]
    return {'本日': 本日, '日词': 日, '引': 引, '令': 令, '线': 线, '日源': 源, '白日': 白日}


def 日之述(b):
    """乙层【一】之「本章之日」一句。"""
    if b['本日'] is None:
        return '本章日号：取不着（表无本章之行，白文亦未落）'
    号 = '%s·%d' % (b['线'], b['本日']) if b['线'] else '第%d' % b['本日']
    if b['日源'] == '白文':
        return '本章为第%d天（取自白文）' % b['本日']
    源 = b['日源']
    if 源 == '总纲＝锁定行':
        照 = '照总纲 %s，施工表锁定行同' % 号
    elif 源.startswith('锁定行≠总纲'):
        照 = '照施工表锁定行 %s，而总纲作 %s——二表自不合，查' % (号, 源.split('总纲 ')[1])
    else:
        照 = '照%s %s' % (源, 号)
    if b['白日'] is None:
        return '本章日号：白文未落（%s）' % 照
    if b['白日'] == b['本日']:
        return '本章为 %s（%s；白文亦落）' % (号, 照)
    return '本章为 %s（%s；白文所落第%d与表不合——查）' % (号, 照, b['白日'])


