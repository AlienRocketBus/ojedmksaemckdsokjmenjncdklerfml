无拍式 = re.compile(r'^无\s*[（(]\s*本章之职\s*[：:]\s*([^）)\n]*)')


def 无拍之由(拍):
    """叫绝之拍写「无（本章之职：…）」→ 其职（≥4 字）；不是此式或职不足 → None。"""
    m = 无拍式.match(拍 or '')
