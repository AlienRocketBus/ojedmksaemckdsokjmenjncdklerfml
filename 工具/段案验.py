def 字数之带(节文):
    """段案本章之节里首个「字数：」其句（至「。」「；」或行末）中之带「a—b」→ (底, 顶)；无「字数：」→ None；有而认不出带 → ()。
    ⛔认四位之数（2,300—2,900）——「389:191—193」一类章:行之引⛔认作带。"""
    m = re.search(r'字数\s*[：:]([^\n。；]*)', 节文 or '')
    if not m:
        return None
    x = re.search(r'(?<![\d:：,，])(\d[,，]?\d{3})\s*[—–\-－~～至到]+\s*(\d[,，]?\d{3})(?!\d)', m.group(1))
    if not x:
        return ()
    f = lambda t: int(re.sub(r'[,，]', '', t))
    return f(x.group(1)), f(x.group(2))


